def build_user_prompt(player_message: str, channel: str, is_player: bool) -> str:
    target_type = "спутнику" if is_player else "жителю Азерота"
    return (
        f"Путник говорит тебе ({target_type}): \"{player_message}\"\n\n"
        f"Ответь как ЖИВОЙ {target_type}. Помни свою расу, класс, страхи, желания и прошлое. "
        f"Не ломай 4-ю стену. Не используй мета-термины. Говори от первого лица. "
        f"Только JSON."
    )


def _rep_to_text(rep: int) -> str:
    if rep < -50:
        return "враждебный"
    elif rep < 0:
        return "недружелюбный"
    elif rep < 50:
        return "нейтральный"
    elif rep < 100:
        return "дружелюбный"
    else:
        return "почтённый"